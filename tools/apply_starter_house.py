#!/usr/bin/env python3
"""Connect the cottage's bedroom, foyer, combined living room/kitchen and Elmwatch.
Run AFTER apply_home_furniture.py; the archived v0.3 ZIP is never changed.
House backgrounds remain replaceable at assets/home/foyer.png and
assets/home/living_room_kitchen.png, and no APK is generated by this patch.
"""
from pathlib import Path

p = Path("scripts/game.gd")
src = p.read_text(encoding="utf-8")

def rep(old: str, new: str) -> None:
    global src
    count = src.count(old)
    if count != 1:
        raise SystemExit(f"HOUSE ROOM PATCH ANCHOR FAILED ({count}): {old[:120]!r}")
    src = src.replace(old, new, 1)

rep('var bedroom_art: Node2D\n', 'var bedroom_art: Node2D\nvar house_art: Node2D\n')
rep('\tbedroom_art=null\n\tplayer=null', '\tbedroom_art=null\n\thouse_art=null\n\tplayer=null')

rep('''\t\tbedroom_art.call("apply_styles", data["home_styles"])
\telse:
\t\tvar image=Sprite2D.new()''', '''\t\tbedroom_art.call("apply_styles", data["home_styles"])
\telif map_name in ["foyer", "living"]:
\t\thouse_art=Node2D.new()
\t\thouse_art.set_script(load("res://scripts/house_room_scene.gd"))
\t\thouse_art.call("configure",map_name)
\t\tworld.add_child(house_art)
\telse:
\t\tvar image=Sprite2D.new()''')

rep('''\tif map_name=="bedroom":camera.zoom=Vector2(0.9,0.9)''',
    '''\tif map_name in ["bedroom", "foyer", "living"]:camera.zoom=Vector2(0.9,0.9)''')
rep('''var town_label="YOUR BEDROOM" if current_map=="bedroom" else ("ELMWATCH VILLAGE" if current_map=="town" else "THORNBROOK FOREST")''',
    '''var town_label=str({"bedroom":"YOUR BEDROOM","foyer":"COTTAGE FOYER","living":"LIVING ROOM / KITCHEN","town":"ELMWATCH VILLAGE","forest":"THORNBROOK FOREST"}.get(current_map,"ADVENTURE ODYSSEY"))''')
rep('''\tvar first_hint="Your first day as an adventurer! Look around your room." if current_map=="bedroom" else "Walk east to Thornbrook Forest"''',
    '''\tvar first_hint="Your first day as an adventurer! Look around your room." if current_map=="bedroom" else ("Find the bedroom, living room or front door." if current_map=="foyer" else ("Explore the hearth and kitchen, or return to the foyer." if current_map=="living" else "Walk east to Thornbrook Forest"))''')

rep('''func _walkable(where:Vector2)->bool:
\tif current_map=="bedroom":''', '''func _walkable(where:Vector2)->bool:
\tif current_map=="foyer":
\t\treturn Rect2(390,352,1260,778).has_point(where)
\tif current_map=="living":
\t\tif not Rect2(382,340,1294,758).has_point(where):return false
\t\t# Keep the central dining table and kitchen fixtures solid.
\t\tfor furnishing in [Rect2(885,661,280,205),Rect2(1250,267,430,367),Rect2(475,283,271,207)]:
\t\t\tif furnishing.has_point(where):return false
\t\treturn true
\tif current_map=="bedroom":''')

rep('''\telif current_map=="town" and nearby.size()>0:prompt.text="Talk: %s" % nearby["name"]''',
    '''\telif current_map in ["foyer","living"]:
\t\tvar house_target=_house_target()
\t\tprompt.text="Use: "+house_target if not house_target.is_empty() else "Explore your cottage"
\telif current_map=="town" and nearby.size()>0:prompt.text="Talk: %s" % nearby["name"]''')

rep('''func _interact()->void:
\tif current_map=="bedroom":''', '''func _interact()->void:
\tif current_map in ["foyer","living"]:
\t\t_interact_house()
\t\treturn
\tif current_map=="bedroom":''')

rep('''\t\t\t_show_journal("THE NEXT ROOM",["The hallway is beyond this door. Your kitchen, living room and the way into Elmwatch will open as the cottage is completed.","For now, explore the bedroom, organize your supplies, and try the mirror."])''',
    '''\t\t\t_enter_house_room("foyer",Vector2(1024,640))''')

src += '''
# -- Starter cottage: shared-room travel; bedroom stays a single room. --
func _house_target()->String:
\tif current_map not in ["foyer","living"] or player==null:return ""
\tvar points:Dictionary
\tif current_map=="foyer":
\t\tpoints={"Bedroom":Vector2(1024,335),"Living Room":Vector2(1575,705),"Front Door":Vector2(1024,1082)}
\telse:
\t\tpoints={"Foyer":Vector2(424,710),"Hearth":Vector2(651,506),"Kitchen":Vector2(1480,650)}
\tvar nearest:=182.0
\tvar selected:=""
\tfor key in points.keys():
\t\tvar dist:float=player.position.distance_to(points[key])
\t\tif dist<nearest:
\t\t\tnearest=dist
\t\t\tselected=str(key)
\treturn selected

func _enter_house_room(map_name:String,spawn:Vector2)->void:
\tdata["map"]=map_name
\tdata["pos"]=[spawn.x,spawn.y]
\t_save()
\t_enter_world(map_name,spawn)

func _interact_house()->void:
\tmatch _house_target():
\t\t"Bedroom":
\t\t\t_enter_house_room("bedroom",Vector2(1024,935))
\t\t"Living Room":
\t\t\t_enter_house_room("living",Vector2(525,715))
\t\t"Foyer":
\t\t\t_enter_house_room("foyer",Vector2(1440,705))
\t\t"Front Door":
\t\t\tdata["tutorial_stage"]="outside"
\t\t\t_enter_house_room("town",Vector2(1030,980))
\t\t"Hearth":
\t\t\t_show_journal("A WARM HOME",["A lively fire burns in the hearth. Even adventurers need a safe place to come back to."])
\t\t"Kitchen":
\t\t\t_show_journal("COTTAGE KITCHEN",["Your kitchen is stocked for the journey ahead. Cooking and food upgrades are planned for a later milestone."])
\t\t_:
\t\t\t_message("Move near a doorway or an interesting part of the room, then tap TALK / USE.")
'''
p.write_text(src, encoding="utf-8")
print("STARTER HOUSE PATCH OK: bedroom <-> foyer <-> living; foyer -> Elmwatch.")
